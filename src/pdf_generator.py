def risk_colour(score):

    if score >= 80:
        return colors.red

    if score >= 60:
        return colors.orange

    if score >= 30:
        return colors.gold

    return colors.green

def risk_chart(score):

    drawing = Drawing(350,45)

    chart = HorizontalBarChart()

    chart.x = 0
    chart.y = 5
    chart.height = 20
    chart.width = 250

    chart.data = [[score]]

    chart.valueAxis.valueMin = 0
    chart.valueAxis.valueMax = 100

    chart.categoryAxis.visible = False

    chart.bars[0].fillColor = risk_colour(score)

    drawing.add(chart)

    return drawing

