def build_recommendations(story,user_data):

    story.append(
        Paragraph(
            "Executive Recommendations",
            subtitle_style
        )
    )

    recommendations=[]

    if user_data["failed_logins"]>=5:

        recommendations.append(
            "Enable Multi-Factor Authentication immediately."
        )

    if user_data["days_inactive"]>90:

        recommendations.append(
            "Disable or archive dormant accounts."
        )

    if user_data["is_privileged_user"]:

        recommendations.append(
            "Review privileged role assignments."
        )

    if user_data["risk_score"]>=80:

        recommendations.append(
            "Perform an immediate security investigation."
        )

    recommendations.extend([
        "Rotate passwords and API credentials.",
        "Review access logs.",
        "Implement Zero Trust access policies.",
        "Conduct quarterly IAM audits."
    ])

    for rec in recommendations:

        story.append(
            Paragraph(
                f"• {rec}",
                normal_style
            )
        )

    story.append(PageBreak())

