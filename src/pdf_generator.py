def build_dashboard(story, user_data):

    story.append(Paragraph("Executive Security Dashboard", subtitle_style))
    story.append(Spacer(1, 0.2 * inch))

    score = int(user_data["risk_score"])

    if score >= 80:
        badge = "🔴 CRITICAL"
        badge_color = colors.red
    elif score >= 60:
        badge = "🟠 HIGH"
        badge_color = colors.orange
    elif score >= 30:
        badge = "🟡 MEDIUM"
        badge_color = colors.gold
    else:
        badge = "🟢 LOW"
        badge_color = colors.green

    data = [
        ["Username", str(user_data["username"])],
        ["User ID", str(user_data["user_id"])],
        ["Risk Score", f"{score}/100"],
        ["Risk Tier", badge],
        ["Failed Logins", str(user_data["failed_logins"])],
        ["Days Inactive", str(user_data["days_inactive"])],
        [
            "Privileged User",
            "YES" if user_data["is_privileged_user"] else "NO",
        ],
    ]

    table = Table(data, colWidths=[2.4 * inch, 3.4 * inch])

    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (0, -1), HexColor("#003366")),
                ("TEXTCOLOR", (0, 0), (0, -1), colors.white),

                ("BACKGROUND", (1, 0), (1, -1), colors.whitesmoke),

                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),

                ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),

                ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),

                ("BOTTOMPADDING", (0, 0), (-1, -1), 10),

                ("TOPPADDING", (0, 0), (-1, -1), 10),

                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ]
        )
    )

    story.append(table)

    story.append(Spacer(1, 0.35 * inch))

    story.append(
        Paragraph(
            "<b>Overall Risk Score</b>",
            heading_style,
        )
    )

    story.append(risk_chart(score))

    story.append(
        Paragraph(
            f"<font color='{badge_color.hexval()}'><b>{badge}</b></font>",
            normal_style,
        )
    )

    story.append(Spacer(1, 0.4 * inch))


